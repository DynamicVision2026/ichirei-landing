// Builds the stroke file of the gift ceremony (2026-11-14, part 5): public/strokes/kanjivg-subset.json — the brush-stroke paths, in stroke order, of the characters of engine/lexicon.csv and
// engine/palette.csv (and the twelve characters that can be given back). Source: KanjiVG (https://kanjivg.tagaini.net/), Ulrich Apel and contributors, CC BY-SA 3.0 — here read from the
// directory of its per-character SVG files (the minified `dist/main` of the npm package @madcat/kanjivg 5.0.0 was used: one `<5-digit hex code point>.svg` per character).
// The derived file is under the same licence (CC BY-SA 3.0), as the licence requires: it says so inside, and /credits names KanjiVG and links the licence.
// A character KanjiVG does not hold (many simplified or variant forms) is listed in public/strokes/fallback.txt; the page then fades it in as soft ink instead of writing it.
//
//   node scripts/build-kanjivg-subset.mjs <directory of KanjiVG SVG files>

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2]
if (!dir || !existsSync(dir)) {
  console.error('usage: node scripts/build-kanjivg-subset.mjs <directory of KanjiVG SVG files>')
  process.exit(1)
}

const HAN = /[㐀-鿿豈-﫿\u{20000}-\u{2ffff}]/u
const RETURN_CHARS = '謝同笑憶暖守恩心光敬友家'

/** The needed characters: the kanji column of the lexicon, the kanji and inscription_form columns of the palette, and the twelve return characters. */
function needed() {
  const set = new Set([...RETURN_CHARS])
  const parse = (text) => {
    const rows = []
    let row = []
    let cell = ''
    let q = false
    for (let i = 0; i < text.length; i++) {
      const ch = text[i]
      if (q) {
        if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++ } else if (ch === '"') q = false
        else cell += ch
      } else if (ch === '"') q = true
      else if (ch === ',') { row.push(cell); cell = '' }
      else if (ch === '\n') { row.push(cell); rows.push(row); row = []; cell = '' }
      else if (ch !== '\r') cell += ch
    }
    if (cell || row.length) { row.push(cell); rows.push(row) }
    return rows
  }
  for (const [file, cols] of [['engine/lexicon.csv', ['kanji']], ['engine/palette.csv', ['kanji', 'inscription_form']]]) {
    const [head, ...body] = parse(readFileSync(file, 'utf8'))
    const idx = cols.map((c) => head.indexOf(c))
    for (const r of body) for (const i of idx) for (const c of r[i] ?? '') if (HAN.test(c)) set.add(c)
  }
  return [...set].sort((a, b) => a.codePointAt(0) - b.codePointAt(0))
}

const chars = {}
const missing = []
for (const c of needed()) {
  const file = join(dir, `${c.codePointAt(0).toString(16).padStart(5, '0')}.svg`)
  if (!existsSync(file)) { missing.push(c); continue }
  const paths = [...readFileSync(file, 'utf8').matchAll(/<path id="kvg:[0-9a-f]+-s\d+" d="([^"]+)"/g)].map((m) => m[1])
  if (paths.length === 0) { missing.push(c); continue }
  chars[c] = paths
}

mkdirSync('public/strokes', { recursive: true })
const out = {
  _license: 'Stroke paths derived from KanjiVG (https://kanjivg.tagaini.net/), copyright Ulrich Apel and contributors, licensed under Creative Commons Attribution-Share Alike 3.0 (https://creativecommons.org/licenses/by-sa/3.0/). This derived file is distributed under the same licence.',
  viewBox: 109,
  chars,
}
writeFileSync('public/strokes/kanjivg-subset.json', JSON.stringify(out))
writeFileSync('public/strokes/fallback.txt', `# Characters of the lexicon, the palette and the twelve return characters that KanjiVG does not hold: the gift page fades them in as soft ink instead of writing them stroke by stroke.\n# Generated by scripts/build-kanjivg-subset.mjs — ${missing.length} characters.\n${missing.join('')}\n`)
writeFileSync('public/strokes/LICENSE.txt', `${out._license}\n\nKanjiVG: Ulrich Apel and contributors. Strokes of ${Object.keys(chars).length} characters, in stroke order, one SVG path each.\n`)
console.log(`${Object.keys(chars).length} characters with strokes, ${missing.length} in the fallback list`)
